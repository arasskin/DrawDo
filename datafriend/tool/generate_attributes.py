#!/usr/bin/env python3
"""Generate the one shared attribute enum. IDs are explicit, never inferred."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
schema = json.loads((ROOT/'datafriend/schema/attributes.json').read_text())
entries = sorted(schema['attributes'], key=lambda a:a['id'])
for field in ['id','symbol','name']:
    assert len({a[field] for a in entries}) == len(entries), 'duplicate '+field
assert all(0 < a['id'] <= 0xffffffff for a in entries)
fingerprint = hashlib.sha256(json.dumps(schema,sort_keys=True,separators=(',',':')).encode()).hexdigest()
cpp = '''// Generated by tool/generate_attributes.py. Edit schema/attributes.json.
#pragma once
#include <array>
#include <cstdint>
#include <string_view>
namespace datafriend {
enum class attribute : uint32_t {
'''
cpp += ''.join(f"  {a['symbol']} = {a['id']},\n" for a in entries)
cpp += '};\nstruct attribute_definition { uint32_t id; std::string_view name; };\n'
cpp += f'inline constexpr std::string_view attribute_schema = "{fingerprint}";\n'
cpp += f'inline constexpr std::array<attribute_definition,{len(entries)}> attribute_definitions = {{{{\n'
cpp += ''.join(f"  {{{a['id']}, {json.dumps(a['name'])}}},\n" for a in entries)
cpp += '}};\n} // namespace datafriend\n'
dart = '''// Generated by datafriend/tool/generate_attributes.py. Do not edit.
enum Attribute {
'''
dart += ',\n'.join(f"  {a['symbol']}({a['id']}, '{a['name']}')" for a in entries)
dart += ''';
  const Attribute(this.code, this.wireName);
  final int code;
  final String wireName;
}
'''
dart += f"const datafriendAttributeSchema = '{fingerprint}';\n"
dart += "final attributeIds = Map<String, int>.unmodifiable({\n  for (final a in Attribute.values) a.wireName: a.code,\n});\n"
dart += "final attributeNames = Map<int, String>.unmodifiable({\n  for (final a in Attribute.values) a.code: a.wireName,\n});\n"
outputs = {'datafriend/include/datafriend/attributes.h':cpp,
           'src/app/lib/data/attributes.dart':dart}
for relative, content in outputs.items():
    path = ROOT/relative
    if args.check:
        if not path.exists() or path.read_text()!=content:
            raise SystemExit('stale generated schema: '+relative)
    else:
        path.write_text(content)
